package TheoryClass;

public class Day3Task1 {

	public static void main(String[] args) {
		
		//bitwise operator
		System.out.println(32&36);
		System.out.println(32|36);
		System.out.println(32^36);
		System.out.println(~5);
		System.out.println(~(-5));
		System.out.println(32<<2);
		System.out.println(32>>2);
		
		

	}

}
